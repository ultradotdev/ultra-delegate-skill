#!/usr/bin/env python3
"""Generate the Jev question reference from the production payload builders."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import jev
import jev_qualification as fixtures
from jev_contract import DEFAULT_JEV_POLICY
from jev_questions import ROUTING_QUESTION_VERSION, JUDGING_QUESTION_VERSION


def manifest():
    policy = fixtures.policy()
    packet = fixtures.route_fixture()
    packet["records"] = []  # Examples assert no real capability or outcome.
    routing = jev.route_payload(packet, jev.route_ranking(packet, policy), policy)
    judging = jev.judge_payload(fixtures.judge_fixture(), policy)
    return {
        "schema": "ultra-delegation-jev-questions-v1",
        "routing_version": ROUTING_QUESTION_VERSION,
        "judging_version": JUDGING_QUESTION_VERSION,
        "defaults": DEFAULT_JEV_POLICY,
        "routing": {"state_fields": sorted(routing["state"]),
                    "candidate_fields": sorted(routing["state"]["candidates"][0]),
                    "questions": routing["questions"], "question_hash": jev.hash_value(routing["questions"])},
        "judging": {"state_fields": sorted(judging["state"]),
                    "candidate_fields": sorted(judging["state"]["candidates"][0]),
                    "questions": judging["questions"], "question_hash": jev.hash_value(judging["questions"])},
    }


