def outputs():
    data = manifest()
    return {"jev-questions.json": json.dumps(data, indent=2, sort_keys=True) + "\n", "jev-questions.md": render(data)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1] / "references"
    stale = []
    for name, content in outputs().items():
        target = root / name
        if target.is_symlink():
            print("Refusing symlink generated reference", file=sys.stderr)
            return 1
        if args.write:
            target.write_text(content, encoding="utf-8", newline="\n")
        elif not target.exists() or target.read_text(encoding="utf-8") != content:
            stale.append(name)
    if stale:
        print("Stale generated Jev references: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Jev question references " + ("updated" if args.write else "current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
