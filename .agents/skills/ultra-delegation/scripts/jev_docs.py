             "```json", json.dumps(data["routing"]["questions"], indent=2), "```", "",
             "## How code consumes routing answers", "",
             f"The default suitability threshold is **{p['suitability_threshold']:.2f}**, an experimental operating point. `ambiguous` and `retain` must each be no greater than `1 - threshold`; a candidate's `fit_i` must be at least `threshold`.",
